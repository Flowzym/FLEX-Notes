function clearEntryBar(dialog){dialog.querySelector(':scope > .entry-persistent')?.remove();}
function installEntryBar(dialog,dateInput,follow,sync){
 if(!dateInput||!follow)return;
 const dateField=dateInput.closest('.field,.date-field');if(!dateField)return;
 const bar=document.createElement('section');bar.className='entry-persistent';bar.setAttribute('aria-label','Datum und Nachbereitung');
 dateField.querySelectorAll('.help').forEach(el=>el.remove());
 follow.querySelectorAll('small').forEach(el=>el.remove());
 const followInput=follow.querySelector('input');followInput.classList.add('entry-switch');followInput.setAttribute('role','switch');
 if(followInput.id==='recordFollowUp'){const span=follow.querySelector('span');if(span)span.textContent='Später ergänzen';}
 bar.append(dateField,follow);dialog.querySelector(':scope > .modal-footer').before(bar);
 if(sync){dateInput.addEventListener('input',()=>sync(dateInput.value));dateInput.addEventListener('change',()=>sync(dateInput.value));}
 // Controls generated by the calendar enhancer are outside the scrolling form too.
 enhanceDates();bar.querySelectorAll('input[type=checkbox]').forEach(input=>{input.classList.add('entry-switch');input.setAttribute('role','switch');});
 dialog.querySelectorAll('.meta-details,.entry-edit-meta,.goal-edit-meta').forEach(meta=>{if(![...meta.children].some(el=>el.tagName!=='SUMMARY'&&(el.childElementCount||el.textContent.trim()||el.matches('input,select'))))meta.hidden=true;});
}
