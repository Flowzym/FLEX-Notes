// Horizontal swipes switch the existing tone buttons; vertical scrolling and text editing stay native.
for(const id of ['studentDialog','bulkDialog','optionsDialog']){
 const dialog=document.getElementById(id),body=dialog.querySelector('.modal-body');let gesture=null,suppressUntil=0,motion=[];
 const selector='[data-tone],[data-bulk-tone],[data-editor-tone]';
 function buttons(){return [...body.querySelectorAll(selector)].filter(b=>!b.hidden);}
 function panel(){return body.querySelector('.options,.bulk-options,#editorList');}
 function reduced(){return matchMedia('(prefers-reduced-motion: reduce)').matches;}
 function stopMotion(){motion.forEach(a=>a.cancel());motion=[];body.querySelectorAll('.tone-swipe-ghost').forEach(el=>el.remove());}
 function resetDrag(g){if(!g?.panel)return;const el=g.panel,from=el.style.transform;el.style.transform='';if(from&&el.isConnected&&!reduced())motion.push(el.animate([{transform:from},{transform:'translateX(0)'}],{duration:150,easing:'ease-out'}));}
 function changeWithMotion(button,g,dx){
  const old=g.panel,rect=old?.getBoundingClientRect(),bodyRect=body.getBoundingClientRect(),offset=g.offset||0,scroll=body.scrollTop,sign=dx<0?-1:1;
  const ghost=old&&!reduced()?old.cloneNode(true):null;
  if(ghost){ghost.removeAttribute('id');ghost.querySelectorAll('[id]').forEach(el=>el.removeAttribute('id'));ghost.classList.add('tone-swipe-ghost');ghost.inert=true;ghost.setAttribute('aria-hidden','true');Object.assign(ghost.style,{position:'absolute',left:(rect.left-bodyRect.left-offset-body.clientLeft)+'px',top:(rect.top-bodyRect.top+scroll-body.clientTop)+'px',width:rect.width+'px',margin:'0',pointerEvents:'none',transform:'translateX('+offset+'px)'});}
  if(old)old.style.transform='';button.click();body.scrollTop=scroll;
  const next=panel();if(!ghost||!next)return;
  body.append(ghost);const distance=Math.max(rect.width,180),options={duration:230,easing:'cubic-bezier(.2,.7,.2,1)'};
  const outgoing=ghost.animate([{transform:'translateX('+offset+'px)',opacity:1},{transform:'translateX('+(sign*distance)+'px)',opacity:0}],options);
  const incoming=next.animate([{transform:'translateX('+(-sign*distance)+'px)',opacity:.15},{transform:'translateX(0)',opacity:1}],options);
  motion.push(outgoing,incoming);outgoing.finished.then(()=>ghost.remove(),()=>ghost.remove());
 }
 body.classList.add('tone-swipe-surface');
 body.addEventListener('pointerdown',event=>{
  if(event.isPrimary===false){resetDrag(gesture);gesture=null;return;}
  if(!['touch','pen'].includes(event.pointerType)||buttons().length!==2||event.target.closest('input,textarea,select,[contenteditable],.tag-input,.date-control,.optional-time'))return;
  stopMotion();gesture={id:event.pointerId,x:event.clientX,y:event.clientY,start:performance.now(),horizontal:false,panel:panel(),offset:0};
 },{passive:true});
 body.addEventListener('pointermove',event=>{
  if(!gesture||event.pointerId!==gesture.id)return;const dx=event.clientX-gesture.x,dy=event.clientY-gesture.y;
  if(!gesture.horizontal&&Math.abs(dy)>18&&Math.abs(dy)>Math.abs(dx)){resetDrag(gesture);gesture=null;return;}
  if(Math.abs(dx)>18&&Math.abs(dx)>Math.abs(dy)*1.4){gesture.horizontal=true;if(body.setPointerCapture&&event.isTrusted)body.setPointerCapture(event.pointerId);if(gesture.panel&&!reduced()){gesture.offset=Math.max(-90,Math.min(90,dx*.65));gesture.panel.style.transform='translateX('+gesture.offset+'px)';}}
 },{passive:true});
 body.addEventListener('pointercancel',()=>{resetDrag(gesture);gesture=null;});
 body.addEventListener('pointerup',event=>{
  const g=gesture;gesture=null;if(!g||event.pointerId!==g.id)return;
  const dx=event.clientX-g.x,dy=event.clientY-g.y;
  if(Math.abs(dx)<60||Math.abs(dx)<Math.abs(dy)*1.4||performance.now()-g.start>1000){resetDrag(g);return;}
  const wanted=dx<0?'negative':'positive',button=buttons().find(b=>(b.dataset.tone||b.dataset.bulkTone||b.dataset.editorTone)===wanted);
  if(!button){resetDrag(g);return;}
  // Run the existing click handler before suppressing the touch-generated click.
  if(button.getAttribute('aria-pressed')!=='true'&&!button.classList.contains('active'))changeWithMotion(button,g,dx);else resetDrag(g);
  suppressUntil=performance.now()+450;
 });
 dialog.addEventListener('close',()=>{resetDrag(gesture);gesture=null;stopMotion();});
 body.addEventListener('click',event=>{if(event.isTrusted&&performance.now()<suppressUntil){event.preventDefault();event.stopImmediatePropagation();}},{capture:true});
}
