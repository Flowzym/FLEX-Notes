import 'dart:convert';
import 'dart:io';
import 'package:flutter_test/flutter_test.dart';
import 'package:flex_notizbuch/domain/models.dart';
import 'package:flex_notizbuch/security/backup_codec.dart';

void main() {
  test(
    'chunked backup authenticates order, length, metadata and every chunk',
    () async {
      final plain = jsonEncode({
        'format': 'FLEX-Complete-Backup',
        'data': 'ä' * (BackupCodec.chunkBytes + 31),
      });
      const password = 'Synthetic-test-password';
      final encrypted = await BackupCodec.encrypt(plain, password);
      final original = jsonDecode(encrypted) as Json;
      expect(original['version'], 2);
      expect(original['iterations'], 600000);
      expect((original['chunks'] as List).length, greaterThan(1));
      expect(await BackupCodec.decrypt(encrypted, password), plain);
      final chunks = original['chunks'] as List;
      for (final change in <Json>[
        {'chunks': chunks.reversed.toList()},
        {'chunks': chunks.take(chunks.length - 1).toList()},
        {
          'chunks': [...chunks, chunks.last],
        },
        {'plainBytes': (original['plainBytes'] as int) - 1},
        {'chunkBytes': 2},
        {'iterations': 310000},
        {'noncePrefix': base64Encode(List.filled(8, 0))},
      ]) {
        await expectLater(
          BackupCodec.decrypt(jsonEncode({...original, ...change}), password),
          throwsA(isA<DomainError>()),
        );
      }
      final bytes = base64Decode(chunks.last as String);
      bytes[0] ^= 1;
      await expectLater(
        BackupCodec.decrypt(
          jsonEncode({
            ...original,
            'chunks': [...chunks.take(chunks.length - 1), base64Encode(bytes)],
          }),
          password,
        ),
        throwsA(isA<DomainError>()),
      );
    },
  );
  test(
    'decrypts synthetic envelope generated by original HTML Web Crypto functions in Node',
    () async {
      final decoded = await BackupCodec.decrypt(
        File('test/fixtures/html_encrypted.json').readAsStringSync(),
        'Testpasswort 123!',
      );
      expect(jsonDecode(decoded), {
        'synthetic': true,
        'text': 'Synthetischer Inhalt ÄÖÜ',
      });
    },
  );
  test(
    'encryption roundtrip uses fresh salt and IV and preserves Unicode password spaces',
    () async {
      const plain = '{"synthetic":"ÄÖÜ","records":[]}',
          password = '  Synthetisches Passwort Ä  ';
      final first = await BackupCodec.encrypt(plain, password),
          second = await BackupCodec.encrypt(plain, password);
      expect(first, isNot(second));
      expect(await BackupCodec.decrypt(first, password), plain);
      await expectLater(
        BackupCodec.decrypt(first, password.trim()),
        throwsA(isA<DomainError>()),
      );
    },
  );
  test('modified ciphertext is rejected before reading plaintext', () async {
    final envelope =
        jsonDecode(File('test/fixtures/html_encrypted.json').readAsStringSync())
            as Json;
    final bytes = base64Decode(envelope['ciphertext'] as String);
    bytes[0] ^= 1;
    envelope['ciphertext'] = base64Encode(bytes);
    await expectLater(
      BackupCodec.decrypt(jsonEncode(envelope), 'Testpasswort 123!'),
      throwsA(isA<DomainError>()),
    );
  });
  test('invalid parameters and short passwords are rejected', () async {
    final original =
        jsonDecode(File('test/fixtures/html_encrypted.json').readAsStringSync())
            as Json;
    for (final change in <Json>[
      {'iterations': 1},
      {'version': 2},
      {'salt': 'AA=='},
      {'iv': 'AA=='},
      {'ciphertext': 'AA=='},
    ]) {
      await expectLater(
        BackupCodec.decrypt(
          jsonEncode({...original, ...change}),
          'Testpasswort 123!',
        ),
        throwsA(isA<DomainError>()),
      );
    }
    await expectLater(
      BackupCodec.encrypt('{}', 'kurz'),
      throwsA(isA<DomainError>()),
    );
  });
}
