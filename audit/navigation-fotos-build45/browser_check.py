from pathlib import Path
from playwright.sync_api import sync_playwright, expect
import json
expect.set_options(timeout=30000)
out=Path('/workspace/features45/browser');out.mkdir(exist_ok=True)
with sync_playwright() as p:
 b=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox'])
 c=b.new_context(viewport={'width':390,'height':844},accept_downloads=True)
 page=c.new_page();page.set_default_timeout(45000);errors=[]
 page.on('pageerror',lambda e:errors.append(str(e)))
 page.goto('http://127.0.0.1:8084',wait_until='domcontentloaded')
 page.locator('flt-semantics-placeholder').dispatch_event('click',timeout=30000)
 expect(page.get_by_role('button',name='Aktuell',exact=True)).to_be_visible(timeout=60000)
 print(page.locator('body').aria_snapshot(),flush=True)
 page.screenshot(path=str(out/'live-phone.png'))
 def button(name):
  print('ACTION',name,flush=True)
  return page.get_by_role('button',name=name,exact=True)
 button('Übersicht').click();expect(page.get_by_text('Dieser Bereich wird noch gestaltet.',exact=False)).to_be_visible()
 button('Live').click();button('Aufzeichnung').click();expect(page.get_by_role('button',name='Neuer Schüler',exact=True)).to_be_visible()
 button('Ablauf').click();expect(page.get_by_text('Dieser Bereich wird noch gestaltet.',exact=False)).to_be_visible()
 button('Stundenplan').click();button('Zum Kalender').click();expect(button('Zum Stundenplan')).to_be_visible()
 button('Zum Stundenplan').click();expect(button('Zum Kalender')).to_be_visible()
 page.screenshot(path=str(out/'timetable-phone.png'))
 button('Material').click();button('Scannen').click()
 with page.expect_file_chooser() as fc: button('Bilder / PDF hinzufügen').click()
 fc.value.set_files(['/workspace/features44/browser/probe.jpg'])
 expect(page.get_by_text('1 Seite',exact=True)).to_be_visible(timeout=90000)
 title=page.get_by_role('textbox').nth(0);title.click();page.wait_for_timeout(250);page.keyboard.press('Control+A');page.keyboard.insert_text('Foto Browserprüfung')
 tags=page.get_by_role('textbox').nth(1);tags.click();page.wait_for_timeout(250);page.keyboard.insert_text('Mathe, Arbeitsprobe')
 print(page.locator('body').aria_snapshot(),flush=True)
 page.get_by_label('Fotos (JPG)',exact=True).click()
 button('Bearbeiten').click();expect(button('Spiegeln')).to_be_visible()
 button('Filter').click();page.wait_for_timeout(600)
 warm=page.get_by_label('Warm',exact=True);box=warm.bounding_box();page.mouse.click(box['x']+box['width']/2,box['y']+box['height']/2)
 expect(warm).to_be_checked()
 apply=button('Filter anwenden');box=apply.bounding_box();page.mouse.click(box['x']+box['width']/2,box['y']+box['height']/2)
 expect(apply).to_have_count(0,timeout=90000)
 expect(button('Übernehmen')).to_be_enabled(timeout=90000);button('Übernehmen').click()
 expect(page.get_by_text('Entwurf gesichert',exact=True).first).to_be_visible(timeout=90000)
 page.screenshot(path=str(out/'photo-editor-phone.png'))
 button('Später fortsetzen').click();expect(page.get_by_role('dialog')).to_have_count(0)
 page.reload(wait_until='domcontentloaded');page.locator('flt-semantics-placeholder').dispatch_event('click',timeout=30000)
 button('Weitere Bereiche Mehr').click()
 print(page.locator('body').aria_snapshot(),flush=True)
 button('Entwürfe (1)').click();button('Fortsetzen').click()
 page.get_by_role('textbox').nth(1).click();page.wait_for_timeout(250)
 expect(page.get_by_role('textbox').nth(1)).to_have_value('Mathe, Arbeitsprobe')
 button('Fotos speichern').click();expect(button('Foto bearbeiten')).to_be_visible(timeout=90000)
 expect(page.get_by_text('Mathe · Arbeitsprobe',exact=False)).to_be_visible()
 with page.expect_download() as dl: button('Teilen / Exportieren').click()
 dl.value.save_as(str(out/'exported.jpg'))
 button('Öffnen').click();expect(page.get_by_role('img')).to_be_visible()
 page.screenshot(path=str(out/'photo-viewer-phone.png'))
 assert not errors, errors
 (out/'result.json').write_text(json.dumps({'viewport':[390,844],'navigation':True,'draft_resumed':True,'tags':True,'jpeg_export':True,'photo_edit':True,'page_errors':errors},indent=2))
 b.close()
